bool AimToPadExtra(const NativeLease& lease,float desiredYaw,float semanticPitch,Input* out) noexcept {
    if(!out || !lease.object || !lease.profile || !lease.control ||
       !std::isfinite(desiredYaw) || !std::isfinite(semanticPitch) ||
       std::fabs(semanticPitch)>kExtraPi/2)return false;
    __try {
        if(!Readable(lease.object,0x355) || !Readable(lease.control,12) ||
           At<const void*>(lease.object,0x30)!=lease.control || At<LONG>(lease.control,8)<=0 ||
           (lease.object[0x18]&4) || lease.object[0x2E8])return false;
        const std::uint32_t input=lease.profile->inputRva;
        if(input==0x31ED90) {
            if(!ExtraMatches(kDeiroiLook))return false;
            // 31EF18..80: F44 += -.01 * pad3C; there is no native pad54 input.
            return EulerExtra(lease,0xF44,static_cast<double>(0.01f),false,desiredYaw,semanticPitch,out);
        }
        if(input==0x4A8FD0 || input==0x42D560) {
            if(!ExtraMatches(kInsectLook) || !Readable(lease.object+0x1000,8))return false;
            if(!(lease.object[0x1000]&2) || At<int>(lease.object,0x1004)!=0) {
                out->yaw=0;out->pitch=0;return true;
            }
            // E30 is the cling target quaternion; E40 is the smoothed result.
            return ClingExtra(lease,0xE30,0x1070,desiredYaw,semanticPitch,out);
        }
        if(input==0x4E0010) {
            if(!ExtraMatches(kNephilaLook) || !Readable(lease.object+0xF30,1))return false;
            if(!(lease.object[0xF30]&2)){out->yaw=0;out->pitch=0;return true;}
            return ClingExtra(lease,0xE10,0,desiredYaw,semanticPitch,out);
        }
        if(input==0x368310) {
            double step=0;
            if(!ExtraMatches(kLargeDangoLook) || !ReadExtra(lease,0x14CC,&step))return false;
            return EulerExtra(lease,0xFB0,step,true,desiredYaw,semanticPitch,out);
        }
        if(input==0x3A4AF0) {
            if(!ExtraMatches(kMermanLook) || !Readable(lease.object+0x17F0,8))return false;
            const auto state=At<std::uint32_t>(lease.object,0x17F0);
            if(state>=4 || (lease.object[0x17F4]&4)){out->yaw=0;out->pitch=0;return true;}
            double step=0;
            if(!MermanStepExtra(lease,state,&step))return false;
            if(step==0){out->yaw=0;out->pitch=0;return true;}
            return EulerExtra(lease,0x1764,step,false,desiredYaw,semanticPitch,out);
        }
        if(input==0x3B3ED0) {
            if(!ExtraMatches(kFlyingDynoLook) || !Readable(lease.object+0x10E0,1))return false;
            if(!(lease.object[0x10E0]&2)){out->yaw=0;out->pitch=0;return true;}
            // The native angular cap follows scaling. Invert the original .2
            // scale; using the cap as the divisor would overshoot small errors.
            const double step=static_cast<double>(0.2f);
            return EulerExtra(lease,0x10B0,step,true,desiredYaw,semanticPitch,out);
        }
        if(input==0x3C0850) {
            if(!ExtraMatches(kShellFishLook) || !Readable(lease.object+0x1570,1))return false;
            if(lease.object[0x1570]&2){out->yaw=0;out->pitch=0;return true;}
            return EulerExtra(lease,0x1000,static_cast<double>(0.1f),true,desiredYaw,semanticPitch,out);
        }
        if(input==0x3D60F0) {
            if(!ExtraMatches(kSpinnerLook))return false;
            return EulerExtra(lease,0xFC0,static_cast<double>(0.1f),true,desiredYaw,semanticPitch,out);
        }
        if(input==0x3E2140) {
            if(!ExtraMatches(kSquidLook) || !Readable(lease.object+0x1260,1))return false;
            if(!(lease.object[0x1260]&2)){out->yaw=0;out->pitch=0;return true;}
            return EulerExtra(lease,0x12C0,static_cast<double>(0.1f),true,desiredYaw,semanticPitch,out);
        }
        if(input==0x3EE300) {
            if(!ExtraMatches(kTimeShipLook) || !Readable(lease.object+0x1168,1))return false;
            if(lease.object[0x1168]&2){out->yaw=0;out->pitch=0;return true;}
            return TimeShipExtra(lease,desiredYaw,semanticPitch,out);
        }
        if(input==0x4ACD70 || input==0x4BC8B0) {
            if(!ExtraMatches(kMonsterLook) || !Readable(lease.object+0x8B0,1))return false;
            if(!(lease.object[0x8B0]&2)){out->yaw=0;out->pitch=0;return true;}
            return EulerExtra(lease,0x14F4,static_cast<double>(0.01f),false,desiredYaw,semanticPitch,out);
        }
        if(input==0x4F9540 || input==0x4F74D0) {
            if(!ExtraMatches(kCarrierLook) || !Readable(lease.object+0xDF0,4))return false;
            if(At<int>(lease.object,0xDF0)!=0){out->yaw=0;out->pitch=0;return true;}
            return EulerExtra(lease,0x604,static_cast<double>(0.01f),false,desiredYaw,semanticPitch,out);
        }
        if(input==0x52EF70) {
            if(!ExtraMatches(kUfo507Look))return false;
            return EulerExtra(lease,0x6D4,static_cast<double>(0.1f),false,desiredYaw,semanticPitch,out);
        }
        if(input==0x5371C0) {
            double step=0;
            if(!ExtraMatches(kUfo515Look) || !ReadExtra(lease,0x10C8,&step))return false;
            return EulerExtra(lease,0x10B4,step,false,desiredYaw,semanticPitch,out);
        }
        if(input==0x30E300) {
            if(!ExtraMatches(kAlienTrailerLook))return false;
            double target=0,previous=0;
            if(!ReadExtra(lease,0x1084,&target) || !ReadExtra(lease,0xCC0,&previous))return false;
            const double error=std::remainder(static_cast<double>(desiredYaw)-target,2*kExtraPi);
            // Native shield carrier turns through left/right MAB actions, not
            // an angular integrator: CC0=-pad3C, start abs>.3, retain abs>=.1.
            // Close the same absolute-heading loop with those native thresholds.
            const double threshold=std::fabs(previous)>=static_cast<double>(0.1f) ?
                static_cast<double>(0.1f) : static_cast<double>(0.3f);
            out->yaw=std::fabs(error)<=threshold ? 0.0f : error>0 ? -1.0f : 1.0f;
            out->pitch=0;return true;
        }
        if(input==0x4F3810) {
            if(!ExtraMatches(kDropBoatLook))return false;
            // The native drop boat has no look axes. Its mission/native path
            // still ticks and its actual payload skill remains available.
            out->yaw=0;out->pitch=0;return true;
        }
        return false;
    } __except(EXCEPTION_EXECUTE_HANDLER) {return false;}
}
