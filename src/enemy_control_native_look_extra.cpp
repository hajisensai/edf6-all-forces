template<std::size_t N> bool ExtraMatches(const ExtraLookPrint (&prints)[N]) noexcept {
    if(!image)return false;
    for(const auto& print:prints)
        if(!Readable(image+print.rva,sizeof(print.bytes)) ||
           std::memcmp(image+print.rva,print.bytes,sizeof(print.bytes))!=0)return false;
    return true;
}
constexpr double kExtraPi=3.14159265358979323846;
float ExtraAxis(double error,double step) noexcept {
    const double raw=error/step;
    return static_cast<float>(raw<-1 ? -1 : raw>1 ? 1 : raw);
}
bool ReadExtra(const NativeLease& lease,std::size_t at,double* out) noexcept {
    if(!Readable(lease.object+at,sizeof(float)))return false;
    *out=At<float>(lease.object,at);return std::isfinite(*out);
}
bool EulerExtra(const NativeLease& lease,std::size_t target,double step,bool pitch,
                float yaw,float elevation,Input* out) noexcept {
    double targetYaw=0,targetPitch=0;
    if(!std::isfinite(step) || step<0 || !ReadExtra(lease,target+(pitch ? 4u : 0u),&targetYaw) ||
       (pitch && !ReadExtra(lease,target,&targetPitch)))return false;
    if(step==0){out->yaw=0;out->pitch=0;return true;}
    const float rawYaw=-ExtraAxis(std::remainder(static_cast<double>(yaw)-targetYaw,2*kExtraPi),step);
    const float rawPitch=pitch ? ExtraAxis(-static_cast<double>(elevation)-targetPitch,step) : 0.0f;
    out->yaw=rawYaw;out->pitch=rawPitch;return true;
}
// The native quaternion builder 0x63F90 stores local axes as rows. Taking dot
// products is the inverse quaternion rotation, without reading rendered matrices.
bool LocalExtra(const NativeLease& lease,std::size_t target,float yaw,float elevation,
                double* localX,double* localY,double* localZ) noexcept {
    if(!Readable(lease.object+target,4*sizeof(float)))return false;
    double x=At<float>(lease.object,target),y=At<float>(lease.object,target+4),
           z=At<float>(lease.object,target+8),w=At<float>(lease.object,target+12);
    const double length=x*x+y*y+z*z+w*w;
    if(!std::isfinite(length) || length<0.000001)return false;
    const double scale=1/std::sqrt(length);x*=scale;y*=scale;z*=scale;w*=scale;
    const double cp=std::cos(static_cast<double>(elevation));
    const double dx=std::sin(static_cast<double>(yaw))*cp,dy=std::sin(static_cast<double>(elevation)),
                 dz=std::cos(static_cast<double>(yaw))*cp;
    *localX=(1-2*(y*y+z*z))*dx+2*(x*y+z*w)*dy+2*(x*z-y*w)*dz;
    *localY=2*(x*y-z*w)*dx+(1-2*(x*x+z*z))*dy+2*(y*z+x*w)*dz;
    *localZ=2*(x*z+y*w)*dx+2*(y*z-x*w)*dy+(1-2*(x*x+y*y))*dz;
    return std::isfinite(*localX) && std::isfinite(*localY) && std::isfinite(*localZ);
}
bool ClingExtra(const NativeLease& lease,std::size_t target,std::size_t velocity,
                float yaw,float elevation,Input* out) noexcept {
    double x=0,y=0,z=0,previous=0;
    if(!LocalExtra(lease,target,yaw,elevation,&x,&y,&z) ||
       (velocity && !ReadExtra(lease,velocity,&previous)))return false;
    // Rotation is restricted to the native cling surface. At a surface-normal
    // aim there is no unique heading; stop rather than invent a turn direction.
    const double error=x*x+z*z<0.00000001 ? 0.0 : std::atan2(x,z);
    // InsectBase: v'=.9*v + .1*(-rawYaw*.05), target*=Ry(v').
    // Nephila has the same signed .05 step and no velocity interpolation.
    const double alpha=velocity ? static_cast<double>(0.1f) : 1.0;
    const float raw=ExtraAxis(error-(1-alpha)*previous,-static_cast<double>(0.05f)*alpha);
    out->yaw=raw;out->pitch=0;return true;
}
// Numeric DSGO getters match 52DE0/52E50/52F50 but do not evaluate type-4
// expressions. Reading the native turn-rate handle twice must not execute a VM
// or consume action RNG before the original input tick evaluates it.
struct ExtraNode {const unsigned char* pointer=nullptr;unsigned type=0;bool runtime=false;};
bool ExtraOffset(const unsigned char* base,std::int64_t offset,std::size_t bytes,
                 const unsigned char** result) noexcept {
    if(!base)return false;
    const auto address=reinterpret_cast<std::uintptr_t>(base);
    std::uintptr_t next=0;
    if(offset<0) {
        const auto distance=static_cast<std::uint64_t>(-(offset+1))+1;
        if(distance>address)return false;next=address-static_cast<std::uintptr_t>(distance);
    } else {
        const auto distance=static_cast<std::uint64_t>(offset);
        if(distance>UINTPTR_MAX-address)return false;next=address+static_cast<std::uintptr_t>(distance);
    }
    const auto p=reinterpret_cast<const unsigned char*>(next);
    if(!Readable(p,bytes))return false;*result=p;return true;
}
bool ExtraSgoNode(const unsigned char* tree,std::uint32_t index,ExtraNode* out) noexcept {
    if(!Readable(tree,0x58))return false;
    const unsigned char* at=nullptr;
    if(index<At<std::uint64_t>(tree,0x18)) {
        const auto mapping=At<const unsigned char*>(tree,8);
        if(!ExtraOffset(mapping,static_cast<std::int64_t>(index)*4,4,&at))return false;
        const auto mapped=At<std::uint32_t>(at,0);
        if(mapped!=UINT32_MAX) {
            const auto nodes=At<const unsigned char*>(tree,0x28);
            if(!ExtraOffset(nodes,static_cast<std::int64_t>(mapped)*0x28,0x28,&at))return false;
            *out={at,At<std::uint16_t>(at,0x20),true};return true;
        }
    }
    const auto blob=At<const unsigned char*>(tree,0x50);
    if(!Readable(blob,16) || At<std::uint32_t>(blob,0)!=0x4F475344u ||
       index>=At<std::uint32_t>(blob,8))return false;
    const auto offset=static_cast<std::int64_t>(At<std::int32_t>(blob,12))+static_cast<std::int64_t>(index)*16;
    if(!ExtraOffset(blob,offset,16,&at))return false;
    *out={at,At<std::uint32_t>(at,8),false};return true;
}
bool MermanStepExtra(const NativeLease& lease,std::uint32_t state,double* step) noexcept {
    if(!Readable(lease.object+0x1740,12))return false;
    const auto tree=At<const unsigned char*>(lease.object,0x1740);
    const auto index=At<std::uint32_t>(lease.object,0x1748);
    ExtraNode parent{},number{};
    if(!ExtraSgoNode(tree,index,&parent) || parent.type!=3)return false;
    const unsigned char* child=nullptr;
    if(parent.runtime) {
        const auto container=At<const unsigned char*>(parent.pointer,0);
        if(!Readable(container,0x60) || state>=At<std::uint64_t>(container,0x58) ||
           !ExtraOffset(At<const unsigned char*>(container,0x48),static_cast<std::int64_t>(state)*4,4,&child))return false;
    } else {
        const unsigned char* container=nullptr;
        if(!ExtraOffset(parent.pointer,At<std::int32_t>(parent.pointer,0),16,&container) ||
           state>=At<std::uint32_t>(container,12) ||
           !ExtraOffset(container,static_cast<std::int64_t>(At<std::int32_t>(container,8))+static_cast<std::int64_t>(state)*4,4,&child))return false;
    }
    if(!ExtraSgoNode(tree,At<std::uint32_t>(child,0),&number) || number.type!=0)return false;
    const float nativeValue=static_cast<float>(At<double>(number.pointer,0));
    // 3A4C14 multiplies raw input by .02 before the native turn-rate lookup.
    *step=static_cast<double>(nativeValue)*static_cast<double>(0.02f);
    return std::isfinite(*step) && *step>=0;
}
bool TimeShipExtra(const NativeLease& lease,float yaw,float elevation,Input* out) noexcept {
    double x=0,y=0,z=0;
    if(!LocalExtra(lease,0xFC0,yaw,elevation,&x,&y,&z))return false;
    // Native delta = Ry(-rawYaw*.1) * Rx(rawPitch*.1); target*=delta.
    if(y<-1)y=-1;if(y>1)y=1;
    out->yaw=-ExtraAxis(std::atan2(x,z),static_cast<double>(0.1f));
    out->pitch=ExtraAxis(-std::asin(y),static_cast<double>(0.1f));return true;
}
