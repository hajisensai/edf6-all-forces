bool EnemyControlNativeNetworkPoseReady(const enemy_native::NativeLease& lease) noexcept {
    __try {
        if(!PoseImage() || !lease.object || !lease.control || !Readable(lease.profile,sizeof(*lease.profile)) ||
           !Readable(lease.object,kPoseDestroyed+1) || !Readable(lease.control,12) || At<LONG>(lease.control,8)<=0 ||
           At<const void*>(lease.object,kPoseControl)!=lease.control || (lease.object[0x18]&4) || lease.object[kPoseDestroyed])return false;
        for(std::size_t i=0;i<sizeof(kPoseRows)/sizeof(kPoseRows[0]);++i) {
            const auto& row=kPoseRows[i];
            if(lease.profile->vtableRva!=row.primary)continue;
            if(!row.verified || lease.profile->profileHash!=row.profileHash || !PoseProfile(*lease.profile,kPoseInputProfiles[i]) ||
               At<const void*>(lease.object,0)!=image+row.primary ||
               At<const void*>(lease.object,kPoseSubobject)!=image+row.secondary ||
               !PoseImageAt(row.primary-8,8) || !PoseImageAt(row.secondary-8,10*8))return false;
            if(PoseSharedProfile(row.primary) && !PoseSharedCode())return false;
            const auto primaryCol=At<const unsigned char*>(image+row.primary-8,0);
            const auto secondaryCol=At<const unsigned char*>(image+row.secondary-8,0);
            if(secondaryCol!=image+row.col || !PoseCol(primaryCol,row,0) || !PoseCol(secondaryCol,row,0x120))return false;
            for(std::size_t slot=0;slot<4;++slot)
                if(At<const void*>(image+row.secondary,(slot+5)*8)!=image+row.slot[slot] || !PoseCode(row.slot[slot]))return false;
            return true;
        }
    } __except(EXCEPTION_EXECUTE_HANDLER) {}
    return false;
}
