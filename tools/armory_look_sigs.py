"""The code the 整备 look page (src/armory_look.cpp, src/armory_look_logic.h) rests on, as byte signatures read from
EDF.dll (TimeDateStamp 0x678CCB46): writes src/armory_look_signatures.inc. tests/armory_look_native_audit.py checks the
.inc against the game's EDF.dll and the page's GameStatus offsets against the code below.

The page writes what the stock screens write (no stock function is called but the worn outfit's reader): the outfit
popup's items (GS+0x6E94), the colour screen's setter (the selected swatch of a class / outfit / channel), and reads
what the colour screen reads (the 12 swatches, the unlock flag). A change there means the layout may have changed: the
page stays off.

    python tools/armory_look_sigs.py [EDF.dll]
"""
from __future__ import annotations

import os
import sys

HERE = os.path.dirname(os.path.abspath(__file__))
sys.path.insert(0, HERE)
import room_preview_sigs  # noqa: E402  (image(): the TimeDateStamp check)

INC = os.path.join(HERE, '..', 'src', 'armory_look_signatures.inc')

# (rva, size, what it holds)
SIGNATURES: tuple[tuple[int, int, str], ...] = (
    (0x0D8700, 0x28, 'the worn outfit (GS, player): GS+0x6E94 + player*0x3E60, -1 the mission\'s (jmp 0xE10F0); called'),
    (0x8AB300, 0x0F, 'the outfit change unlocked: byte GS+0x300 (the soldier screen offers the popup only then)'),
    (0x8AD5DC, 0x31, 'the stock outfit item 2 (0x8AD5C0): GS+0x6E94 + [screen+0x798]*0x3E60 = 2, then the popup closed'),
    (0x882790, 0x42, 'the colour screen\'s setter (screen, ch, idx): GS+0x7070 + player*0x3E60 + ((cls*4+outfit)*2+ch)*0xC4 '
                     '= idx, then 0x881F40 (msg 9 / 3 / 8: the view rebuilt from GS)'),
    (0x8817A3, 0x57, 'the colour screen\'s swatch read: the selected index, then the float4 at GS + (player*0x3E6 + 0x6FB + '
                     'idx)*0x10 + ((cls*4+outfit)*2+ch)*0xC4'),
)


def render(img: bytes) -> str:
    lines = ['// Generated by tools/armory_look_sigs.py from EDF.dll 0x678CCB46: do not edit. (armory_look.cpp Install)']
    for i, (rva, size, what) in enumerate(SIGNATURES):
        data = ','.join(f'0x{b:02X}' for b in img[rva:rva + size])
        lines.append(f'// {what}')
        lines.append(f'constexpr unsigned char kSig{i}[]={{{data}}};')
    lines.append('constexpr Signature kSignatures[]={')
    lines += [f'    {{0x{rva:X},kSig{i},sizeof(kSig{i})}},' for i, (rva, _, _) in enumerate(SIGNATURES)]
    lines.append('};')
    return '\n'.join(lines) + '\n'


def main(argv: list[str]) -> int:
    import gamedir
    path = argv[1] if len(argv) > 1 else os.path.join(gamedir.find_or_dev(), 'EDF.dll')
    _, img = room_preview_sigs.image(path)
    with open(INC, 'w', encoding='utf-8', newline='\n') as f:
        f.write(render(img))
    print(f'wrote {os.path.normpath(INC)}: {len(SIGNATURES)} signatures')
    return 0


if __name__ == '__main__':
    sys.exit(main(sys.argv))
