"""EDF6VehicleCrew.ini's keys: the one table the plugin's Config and the shipped ini are made from (2026-11-27,
docs/reviews/design-review-1126.md P5 / P6). tools/gen_config.py writes from it:
  src/config.inc         the Config fields (config.h), the reads (plugin.cpp LoadConfig) and the range checks
                         (plugin.cpp Validate), and the retired keys' warnings (plugin.cpp IgnoreRetired)
  EDF6VehicleCrew.ini    the shipped ini: HEADER, each shipped key's comment lines and its default, TAIL
CI and tools/check.py run gen_config.py --check; tools/selftest.py parses the generated ini back against KEYS.

A key (Key, K for short), in the shipped ini's order:
  name      the ini key
  field     its Config member (None: no member, the ini's value read elsewhere: see read)
  type      BOOL / FLOAT / INT / DWORD the member's type; TEXT: a value this table only ships (field None)
  default   the default: True / False for a BOOL, else the ini's text ('0x48', '1.0', '-5', 'auto'); the member's
            initialiser is the same number (a FLOAT's with '.0f' / 'f' added), or cxx when the ini's text is no number
  lo, hi    the range Validate keeps it in: C++ expressions (plugin.cpp's scope; 'n.heliRange': another key's value,
            checked after the keys with fixed ranges)
  check     'clamp' a value out of range is clamped and logged (Fix / FixInt); 'nonzero' the same, 0 left alone (off);
            'reset' a value out of range is logged and the default used; 'hand' plugin.cpp Validate checks it itself
  read      'gen' read by the generated LoadConfig code; 'hand' plugin.cpp LoadConfig reads it itself (a parser of its
            own, a fallback key, a bit of a mask); else the file that reads it (support_config.cpp's own section
            reader, the installer)
  old       an older key read as the default when this one is missing
  cxx       the member's initialiser when it differs from default's text
  shipped   False: read but not in the shipped ini (developer and test keys)
  why       the comment lines before its range check; why_after: a comment after it
  doc       the comment lines before the member (a group's heading); note: its trailing comment (more lines continue it)
  ini       the shipped ini's lines before the key: comments, blank lines, the group headings

Changing a key: edit its entry, run python tools/gen_config.py, commit config_keys.py, src/config.inc and
EDF6VehicleCrew.ini together. A new key is appended where its group is; the installer only adds keys a player's ini
lacks (tools/installer.py), so a changed default reaches only new installs and the inis that never had the key.
A key no longer read moves to RETIRED (out of KEYS): an old ini that still has it is told once that it is ignored.
"""
