"""Writes src/calls.inc, the plugin's side of the call table (src/airstrike.cpp includes it), from tools/calls.py:
  kCalls       the supports the plugin flies (Call), in CALLS order: the map's support bar's (src/support_dispatch.cpp
               catalog 0..kCallCount-1); a sortie's pass (crew.h SortiePass, 0 none), its second wave (`then`: another
               kCalls index, -1 none; after ms) and last what it costs on the map (calls.Call.pt)
  kCallLabels  their names on the bar (the SC names their weapons carried)
  kCallRows    every live weapon row tools/call_weapons.py installs (vehicle requests, thrown drones, guns): its id, its
               weapon SGO under Mods/WEAPON and the object SGO a vehicle request brings under Mods/OBJECT (nullptr: none)
  kMovedRows   the placeholders' ids of the supports moved to the map (2026-10-26, calls.Call.on_map): the plugin un-owns
               them at every save load
  kThrows      the thrown drones (Robot Bombs, brings 'throw'): the marker's float bits, the drone, its fuel
  kStrikes     the strikes on the map's bar after the airdrops (calls.STRIKES: the barrages, then the ultimate): its kind,
               its barrage kind (src/barrage_plan.h, -1 the ultimate), its damage (a barrage's each round's, the ultimate's
               the show's), its pt, its log name, its catalog key and its label

  python tools/gen_calls.py            write it
  python tools/gen_calls.py --check    exit 1 when the committed file is not what this would write (CI)
"""
from __future__ import annotations

import os
import sys

HERE = os.path.dirname(os.path.abspath(__file__))
sys.path.insert(0, HERE)
import calls  # noqa: E402

OUT = os.path.normpath(os.path.join(HERE, '..', 'src', 'calls.inc'))
BRINGS = {'jets': 'Brings::jets', 'helis': 'Brings::helis', 'sub': 'Brings::sub'}


def _wstr(s: str) -> str:
    return 'L"' + s.replace('\\', '\\\\').replace('"', '\\"') + '"'


def _float(x: float) -> str:
    return f'{float(x):.1f}f'


def _opt(enum: str, value: str) -> str:
    return f'{enum}::{value}' if value else 'std::nullopt'


def _call(c: calls.Call) -> str:
    sortie = 1 + calls.SORTIE_PASSES.index(c.sortie) if c.sortie else 0
    then = [f.id for f in calls.FLOWN].index(c.then) if c.then else -1
    return (f'    {{{_float(c.mark)},{BRINGS[c.brings]},{_opt("JetRole", c.role)},{_opt("HeliBody", c.body)},'
            f'{c.count},{c.fuel_sec},{"true" if c.follow else "false"},"{c.log}",{_wstr(c.id)},{sortie},{then},'
            f'{c.then_after * 1000}u,{c.pt}u}},')


def _throw(c: calls.Call) -> str:
    return f'    {{0x{calls.mark_bits(c):08X}u,ThrownDrone::{c.drone},{c.fuel_sec},"{c.log}",{_wstr(c.id)}}},'


def _strike(c: calls.Call) -> str:
    barrage = calls.BARRAGE_KINDS.index(c.barrage) if c.brings == 'barrage' else -1
    key = c.id[len(calls.ID_PREFIX):]
    return (f'    {{StrikeKind::{c.brings},{barrage},{_float(c.damage)},{c.pt}u,"{c.log}",{_wstr(key)},'
            f'{_wstr(calls.call_name(c, "SC"))}}},')


def _row(c: calls.Call) -> str:
    weapon = _wstr(f'{c.id.upper()}.SGO')
    obj = _wstr(f'{c.vehicle.upper()}.SGO') if c.vehicle else 'nullptr'
    return f'    {{{_wstr(c.id)},{weapon},{obj}}},'


def render() -> str:
    lines = [
        '// Generated by tools/gen_calls.py from tools/calls.py: do not edit (CI checks it is current).',
        '// Included by src/airstrike.cpp after its Brings / Call / CallRow definitions.',
        '',
        "// The supports the plugin flies from the map's support bar (src/support_dispatch.cpp catalog 0..kCallCount-1), in "
        'tools/calls.py CALLS order.',
        'const Call kCalls[]={',
        *[_call(c) for c in calls.FLOWN],
        '};',
        'constexpr int kCallCount=static_cast<int>(sizeof(kCalls)/sizeof(kCalls[0]));',
        '// kCalls\' names on the in-mission pick\'s banner (the SC names the weapons carry).',
        'const wchar_t* const kCallLabels[]={',
        *[f'    {_wstr(calls.call_name(c, "SC"))},' for c in calls.FLOWN],
        '};',
        'static_assert(sizeof(kCallLabels)/sizeof(kCallLabels[0])==kCallCount,"a label per call");',
        '// Every live weapon row tools/call_weapons.py installs (vehicle requests, thrown drones, guns): its id, weapon SGO, '
        'object SGO.',
        'const CallRow kCallRows[]={',
        *[_row(c) for c in calls.CALLS if not c.on_map],
        '};',
        'constexpr int kCallRowCount=static_cast<int>(sizeof(kCallRows)/sizeof(kCallRows[0]));',
        "// The rows of the supports moved to the map (2026-10-26): their placeholders' ids, un-owned at every save load.",
        'const wchar_t* const kMovedRows[]={' + ','.join(_wstr(calls.retired_id(c.id)) for c in calls.CALLS if c.on_map)
        + '};',
        'constexpr int kMovedRowCount=static_cast<int>(sizeof(kMovedRows)/sizeof(kMovedRows[0]));',
        '// The thrown drones: their weapons\' AmmoHitSizeAdjust bits (weapon +0x8C4), in tools/calls.py CALLS order.',
        'const Throw kThrows[]={',
        *[_throw(c) for c in calls.CALLS if c.brings == 'throw'],
        '};',
        "// The strikes on the map's support bar (calls.STRIKES: the barrages, then the ultimate), after the airdrops in the "
        'catalog.',
        'const Strike kStrikes[]={',
        *[_strike(c) for c in calls.STRIKES],
        '};',
        'constexpr int kStrikeCount=static_cast<int>(sizeof(kStrikes)/sizeof(kStrikes[0]));',
        '',
    ]
    return '\n'.join(lines)


def main(argv: list[str]) -> int:
    text = render()
    current = None
    if os.path.isfile(OUT):
        with open(OUT, encoding='utf-8', newline='') as f:
            current = f.read().replace('\r\n', '\n')
    if '--check' in argv:
        if current != text:
            print(f'{OUT} is stale: run python tools/gen_calls.py and commit it')
            return 1
        print(f'{OUT} is current')
        return 0
    if current != text:
        with open(OUT, 'w', encoding='utf-8', newline='\n') as f:
            f.write(text)
        print(f'wrote {OUT}')
    return 0


if __name__ == '__main__':
    sys.exit(main(sys.argv[1:]))
