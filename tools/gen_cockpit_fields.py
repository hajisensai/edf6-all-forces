"""Writes src/cockpit_fields.inc, the C++ side of pylib/cockpit_fields.py: the instruments' Field enum
(src/cockpit_instruments.h) and the round classes' CockpitRound (src/hud_cue.h).

  python tools/gen_cockpit_fields.py            write it
  python tools/gen_cockpit_fields.py --check    exit 1 when the committed file is not what this would write (CI)
"""
from __future__ import annotations

import os
import sys

HERE = os.path.dirname(os.path.abspath(__file__))
sys.path.insert(0, os.path.join(HERE, '..', 'pylib'))
import cockpit_fields as cf  # noqa: E402

OUT = os.path.normpath(os.path.join(HERE, '..', 'src', 'cockpit_fields.inc'))


def render() -> str:
    lines = ['// Generated by tools/gen_cockpit_fields.py from pylib/cockpit_fields.py. Do not edit.',
             '// Included by src/cockpit_instruments.h and src/hud_cue.h.',
             '#pragma once',
             'namespace crew::instruments {',
             f'constexpr int kRows={cf.ROWS};',
             'enum Field {']
    at = 0
    for cpp, _py, width in cf.FIELDS:
        lines.append(f'    {cpp}={at},' if width == 1 else f'    {cpp}={at},   // + 0..{width - 1}')
        at += width
    lines.append(f'    count={at}')
    lines.append('};')
    lines.append('}  // namespace crew::instruments')
    lines.append('namespace crew::hudcue {')
    lines.append('enum class CockpitRound { ' + ', '.join(f'{cpp}={i}' for i, (cpp, _tag) in enumerate(cf.ROUND_CLASSES)) + ' };')
    lines.append(f'constexpr int kCockpitRounds={len(cf.ROUND_CLASSES)};')
    lines.append('}  // namespace crew::hudcue')
    return '\n'.join(lines) + '\n'


def main(argv: list[str]) -> int:
    text = render()
    if '--check' in argv:
        try:
            with open(OUT, encoding='utf-8', newline='') as f:
                return 0 if f.read().replace('\r\n', '\n') == text else 1
        except FileNotFoundError:
            return 1
    with open(OUT, 'w', encoding='utf-8', newline='\n') as f:
        f.write(text)
    print('wrote', OUT)
    return 0


if __name__ == '__main__':
    sys.exit(main(sys.argv[1:]))
