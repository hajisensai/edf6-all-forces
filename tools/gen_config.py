"""Writes the plugin's config from tools/config_keys.py (the one table, 2026-11-27):
  src/config.inc         four sections, each taken by defining its macro before the #include:
                           EDF6_CONFIG_FIELDS    the Config members with their defaults (config.h struct Config)
                           EDF6_CONFIG_LOAD      the reads into Config n (plugin.cpp LoadConfig: ReadBool / ReadFloat /
                                                 ReadInt)
                           EDF6_CONFIG_VALIDATE  the range checks (plugin.cpp Validate: Fix / FixInt / Reset), the keys
                                                 whose range names another key's value last
                           EDF6_CONFIG_RETIRED   the retired keys' rows {key, why} (plugin.cpp IgnoreRetired)
  EDF6VehicleCrew.ini    the shipped ini (UTF-8, LF): HEADER, [VehicleCrew], each shipped key's lines and default, TAIL

  python tools/gen_config.py            write them
  python tools/gen_config.py --check    exit 1 when a committed file is not what this would write (CI, tools/check.py)
"""
from __future__ import annotations

import os
import re
import sys

HERE = os.path.dirname(os.path.abspath(__file__))
sys.path.insert(0, HERE)
import config_keys as ck  # noqa: E402

ROOT = os.path.normpath(os.path.join(HERE, '..'))
INC = os.path.join(ROOT, 'src', 'config.inc')
INI = os.path.join(ROOT, 'EDF6VehicleCrew.ini')
CTYPE = {ck.BOOL: 'bool', ck.FLOAT: 'float', ck.INT: 'int', ck.DWORD: 'DWORD'}
NOTE_COLUMN = 36
CHECKS = ('clamp', 'nonzero', 'reset', 'hand')


def initialiser(key: ck.Key) -> str:
    """The member's C++ initialiser: the default's number as a literal of the member's type."""
    if key.type == ck.BOOL:
        return 'true' if key.default else 'false'
    text = key.cxx if key.cxx is not None else key.default
    if key.type == ck.FLOAT and key.cxx is None:
        if re.fullmatch(r'-?\d+', text):
            return text + '.0f'
        if re.fullmatch(r'-?(\d+\.\d*|\.\d+)([eE][-+]?\d+)?', text):
            return text + 'f'
        raise ValueError(f'{key.name}: float default {text!r} is no number')
    if not re.fullmatch(r'-?(0[xX][0-9A-Fa-f]+|\d+)', text):
        raise ValueError(f'{key.name}: {key.type} default {text!r} is no number (set cxx)')
    return text


def members() -> list[ck.Key]:
    return [k for k in ck.KEYS if k.field]


def check_table() -> None:
    names, fields = set(), set()
    retired = {name for name, _ in ck.RETIRED}
    for k in ck.KEYS:
        assert k.name not in names, f'{k.name}: listed twice'
        names.add(k.name)
        assert k.type in CTYPE or k.type == ck.TEXT, f'{k.name}: type {k.type}'
        assert k.check in CHECKS, f'{k.name}: check {k.check}'
        assert (k.lo is None) == (k.hi is None), f'{k.name}: a range needs both ends'
        assert k.check in ('clamp', 'hand') or k.lo is not None, f'{k.name}: {k.check} needs a range'
        assert isinstance(k.default, bool) == (k.type == ck.BOOL), f'{k.name}: default {k.default!r} for {k.type}'
        if k.field:
            assert k.field not in fields, f'{k.field}: two keys'
            fields.add(k.field)
            assert k.type != ck.TEXT, f'{k.name}: a member needs a type'
            assert k.read in ('gen', 'hand'), f'{k.name}: a member is read here (gen / hand), not {k.read}'
        else:
            assert k.read != 'gen' and k.lo is None and not k.old, f'{k.name}: no member to read into'
        assert k.name not in retired, f'{k.name}: retired (RETIRED) but still a key'


def render_inc() -> str:
    out = ['// Generated by tools/gen_config.py from tools/config_keys.py: do not edit (python tools/gen_config.py).',
           '// Each section is taken by defining its macro before the #include (tools/gen_config.py).',
           '#if defined(EDF6_CONFIG_FIELDS)', '#undef EDF6_CONFIG_FIELDS']
    for k in members():
        out += [('    ' + d) if d else '' for d in k.doc]
        decl = f'    {CTYPE[k.type]} {k.field}={initialiser(k)};'
        if k.note:
            out.append(decl.ljust(NOTE_COLUMN - 1) + ' // ' + k.note[0])
            out += [' ' * NOTE_COLUMN + '// ' + n for n in k.note[1:]]
        else:
            out.append(decl)
    out += ['#elif defined(EDF6_CONFIG_LOAD)', '#undef EDF6_CONFIG_LOAD']
    for k in members():
        if k.read != 'gen':
            continue
        f, key = f'n.{k.field}', f'L"{k.name}"'
        if k.type == ck.BOOL:
            out.append(f'    {f}=ReadBool({key},{f});')
        elif k.type == ck.FLOAT:
            out.append(f'    {f}=ReadFloat({key},{f});')
        elif k.type == ck.INT:
            fallback = f'static_cast<DWORD>({f})'
            if k.old:
                fallback = f'static_cast<DWORD>(ReadInt(L"{k.old}",{fallback}))'
            out.append(f'    {f}=ReadInt({key},{fallback});')
        else:
            assert not k.old, k.name
            out.append(f'    {f}=static_cast<DWORD>(ReadInt({key},{f}));')
    out += ['#elif defined(EDF6_CONFIG_VALIDATE)', '#undef EDF6_CONFIG_VALIDATE']
    checked = [k for k in members() if k.lo is not None and k.check != 'hand']
    depends = [k for k in checked if 'n.' in k.lo + k.hi]
    for k in [k for k in checked if k not in depends] + depends:
        out += ['    // ' + w for w in k.why]
        f, lo, hi = f'n.{k.field}', k.lo, k.hi
        if k.check == 'reset':
            assert k.type == ck.FLOAT, k.name
            line = f'Reset("{k.name}",{f},{lo},{hi},{initialiser(k)});'
        elif k.type == ck.FLOAT:
            line = f'Fix("{k.name}",{f},{lo},{hi});'
            if k.check == 'nonzero':
                line = f'if({f}!=0.0f){line}'
        elif k.type == ck.INT:
            line = f'{f}=static_cast<int>(FixInt("{k.name}",{f},{lo},{hi}));'
            if k.check == 'nonzero':
                line = f'if({f}!=0){line}'
        else:
            line = f'{f}=FixInt("{k.name}",static_cast<int>({f}),{lo},{hi});'
            if k.check == 'nonzero':
                line = f'if({f}!=0){line}'
        out.append('    ' + line + (f'   // {k.why_after}' if k.why_after else ''))
    out += ['#elif defined(EDF6_CONFIG_RETIRED)', '#undef EDF6_CONFIG_RETIRED']
    for name, why in ck.RETIRED:
        out.append(f'    {{L"{name}","{why}"}},')
    out += ['#else', '#error define one of EDF6_CONFIG_FIELDS / _LOAD / _VALIDATE / _RETIRED before including config.inc',
            '#endif', '']
    return '\n'.join(out)


def render_ini() -> str:
    out = list(ck.HEADER) + [f'[{ck.SECTION}]']
    for k in ck.KEYS:
        if k.shipped:
            out += list(k.ini) + [f'{k.name}={ck.ini_value(k)}']
    return '\n'.join(out + list(ck.TAIL))


_INCLUDE = re.compile(r'^#define (EDF6_CONFIG_\w+)\n#include "config\.inc"[^\n]*\n', re.M)


def expand(text: str, inc: str | None = None) -> str:
    """A source's text with each config.inc section it includes written out after its #include (the committed
    src/config.inc, or inc): what the compiler sees, for the source checks (tools/selftest.py src, tests/*_guard.py)."""
    if inc is None:
        with open(INC, encoding='utf-8') as f:
            inc = f.read()
    sections = dict(re.findall(r'^#(?:el)?if defined\((EDF6_CONFIG_\w+)\)\n#undef \1\n(.*?)(?=^#el)', inc, re.M | re.S))
    return _INCLUDE.sub(lambda m: m.group(0) + sections[m.group(1)], text)


def read_expanded(rel: str) -> str:
    """expand() of a source under the repository (rel: 'src/config.h')."""
    with open(os.path.join(ROOT, *rel.split('/')), encoding='utf-8') as f:
        return expand(f.read())


def outputs() -> list[tuple[str, str]]:
    check_table()
    return [(INC, render_inc()), (INI, render_ini())]


def main(argv: list[str]) -> int:
    stale = []
    for path, text in outputs():
        current = None
        if os.path.isfile(path):
            with open(path, encoding='utf-8', newline='') as f:
                current = f.read().replace('\r\n', '\n')
        if current == text:
            continue
        if '--check' in argv:
            stale.append(path)
            continue
        with open(path, 'w', encoding='utf-8', newline='\n') as f:
            f.write(text)
        print(f'wrote {path}')
    if stale:
        for path in stale:
            print(f'{path} is stale: run python tools/gen_config.py and commit it')
        return 1
    if '--check' in argv:
        print('src/config.inc and EDF6VehicleCrew.ini are current')
    return 0


if __name__ == '__main__':
    sys.exit(main(sys.argv[1:]))
