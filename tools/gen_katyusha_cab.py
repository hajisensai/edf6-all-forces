"""Writes common/edf/katyusha_cab_gen.h, the Katyusha's firing floor over its cab (test site #36, 2026-11-02: 「让喀秋莎的
向前射角限制一下，他不应该穿过车头设计」): per turntable azimuth, every pylib/katyusha_model.py CAB_AZIMUTH_STEP deg, the
lowest elevation from which every rocket leaves clear of the truck (katyusha_model.py cab_floor_scan / cab_floor_table,
measured on the model tools/make_katyusha.py builds from Root.cpk, read only). common/edf/katyusha_cab.h reads it
(CabFloor); src/katyusha.cpp holds the launcher's bone at or over it, src/launcher.cpp and EDF6AutoTurret choose their
arcs above it.

  python tools/gen_katyusha_cab.py            write it (needs Root.cpk)
  python tools/gen_katyusha_cab.py --check    exit 1 when the committed file is not what this would write (CI). Without
                                              Root.cpk (CI): the file's own record of what it was made from (its `data`
                                              line) is checked against today's inputs (the scan's steps and margin, the
                                              rockets' rays, the launcher's stop, this generator's version) and the file
                                              re-rendered from it must be the file; the model is only re-measured where
                                              the game is.
"""
from __future__ import annotations

import hashlib
import json
import os
import sys

HERE = os.path.dirname(os.path.abspath(__file__))
sys.path.insert(0, os.path.join(HERE, '..', 'pylib'))
import katyusha_model as km  # noqa: E402

OUT = os.path.normpath(os.path.join(HERE, '..', 'common', 'edf', 'katyusha_cab_gen.h'))
VERSION = 1   # this generator's: bump when what it measures or how it writes changes
DATA = '// data: '


def inputs() -> dict:
    """What the file is made from, besides the game's models: the scan's steps and margin, the rockets' rays (their
    starts in the launcher's frame), the launcher's elevation stop and where the rack sits behind the cab."""
    return {'version': VERSION, 'azimuth_step': km.CAB_AZIMUTH_STEP, 'fine_step': km.CAB_FINE_STEP,
            'elev_step': km.CAB_ELEV_STEP, 'margin': km.CAB_MARGIN_DEG, 'reach': km.CAB_RAY_REACH,
            'stop': km.PITCH_STOP_DEG, 'cab_clearance': km.CAB_CLEARANCE,
            'rays': [[round(c, 6) + 0.0 for c in p] for p in km.cab_envelope()]}


def model(game):  # noqa: ANN001, ANN201 - rootcpk.Game -> mdb.Mdb
    """The Katyusha's model as it is written (positions stored as half floats: the round trip)."""
    from mdb import mdb_read, mdb_write
    md, *_ = km.build_model(game)
    return mdb_read(mdb_write(md))


def measure(game) -> dict:  # noqa: ANN001 - rootcpk.Game
    """{'inputs': inputs(), 'model': the measured .mdb's sha256, 'floor': the table (deg, from azimuth 0)}."""
    from mdb import mdb_write
    md = model(game)
    return {'inputs': inputs(), 'model': hashlib.sha256(mdb_write(md)).hexdigest(),
            'floor': km.cab_floor_table(km.cab_floor_scan(md))}


def _f(x: float) -> str:
    """A float literal (always with a point: `1f` is no C++ literal)."""
    s = f'{x:.6g}'
    return (s if '.' in s or 'e' in s else s + '.0') + 'f'


def render(data: dict) -> str:
    floor = data['floor']
    rows = [', '.join(_f(x) for x in floor[k:k + 12]) for k in range(0, len(floor), 12)]
    lines = ['// Generated by tools/gen_katyusha_cab.py from the Katyusha\'s model built from Root.cpk (pylib/katyusha_model.py',
             '// cab_floor_scan, cab_floor_table). Do not edit: python tools/gen_katyusha_cab.py (with the game) rewrites it.',
             DATA + json.dumps(data, sort_keys=True, separators=(',', ':')),
             '#pragma once',
             '',
             'namespace edf::katyusha {',
             '// The launcher\'s lowest elevation (deg) at each turntable azimuth from 0 (the model\'s forward, over the cab)',
             '// every kCabStepDeg deg towards +x; 0 where nothing of the truck is in the rockets\' way.',
             f'constexpr float kCabStepDeg={_f(float(data["inputs"]["azimuth_step"]))};',
             f'constexpr int kCabSteps={len(floor)};',
             'inline constexpr float kCabFloorDeg[kCabSteps]={']
    lines += [f'    {r},' for r in rows]
    lines += ['};', '}  // namespace edf::katyusha']
    return '\n'.join(lines) + '\n'


def _committed() -> str:
    with open(OUT, encoding='utf-8', newline='') as f:
        return f.read().replace('\r\n', '\n')


def recorded() -> dict:
    """The committed file's data line."""
    line = next((x for x in _committed().split('\n') if x.startswith(DATA)), None)
    if line is None:
        raise ValueError(f'{OUT}: no {DATA.strip()} line')
    return json.loads(line[len(DATA):])


def check(game=None) -> str | None:  # noqa: ANN001 - rootcpk.Game
    """None when the committed file is current, else why not (see the module doc: with `game` re-measured, else checked
    against its own record)."""
    text = _committed()
    if game is not None:
        return None if text == render(measure(game)) else 'the model measures otherwise'
    try:
        data = recorded()
    except ValueError as e:
        return str(e)
    if json.loads(json.dumps(inputs())) != data['inputs']:
        return f'made from {data["inputs"]}, the inputs are now {inputs()}'
    if len(data['floor']) * km.CAB_AZIMUTH_STEP != 360:
        return f'{len(data["floor"])} entries do not go round at {km.CAB_AZIMUTH_STEP} deg'
    return None if render(data) == text else 'its table is not what its data line renders'


def main(argv: list[str]) -> int:
    from rootcpk import DEFAULT_GAME, Game
    have = os.path.isfile(os.path.join(DEFAULT_GAME, 'Root.cpk'))
    if '--check' in argv:
        why = check(Game(DEFAULT_GAME) if have else None)
        print(f'{os.path.relpath(OUT)}: {"current" if why is None else "STALE: " + why} '
              f'({"re-measured on the game" if have else "no Root.cpk: checked against its own record"})')
        return 0 if why is None else 1
    if not have:
        print('needs the game (Root.cpk) to build and measure the Katyusha', file=sys.stderr)
        return 2
    with open(OUT, 'w', encoding='utf-8', newline='\n') as f:
        f.write(render(measure(Game(DEFAULT_GAME))))
    print('wrote', OUT)
    return 0


if __name__ == '__main__':
    sys.exit(main(sys.argv[1:]))
