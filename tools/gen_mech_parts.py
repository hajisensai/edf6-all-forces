"""Writes src/mech_parts.inc, the plugin's tables of the custom mech parts (src/mech_loadout.h includes it), from
pylib/mech_parts.py (docs/feature-2026-11-21-mech-custom.md):
  kMechFrames    token, frame file, four-language label
  kMechWeapons   token, label, mount (hand / arm / shoulder), the sides it has a file for, its level in hundredths
  kMechCores     token (the request it is taken from), label, level in hundredths
  kMechRequests  token, label, vehicle file, level (the float the container is configured with) and in hundredths, its
                 frame, its core and its four stock weapons (indexes into the tables above, -1 none)

  python tools/gen_mech_parts.py            write it
  python tools/gen_mech_parts.py --check    exit 1 when the committed file is not what this would write (CI)
"""
from __future__ import annotations

import os
import sys

HERE = os.path.dirname(os.path.abspath(__file__))
sys.path.insert(0, os.path.join(HERE, '..', 'pylib'))
import mech_parts as mp  # noqa: E402

OUT = os.path.normpath(os.path.join(HERE, '..', 'src', 'mech_parts.inc'))


def _s(text: str) -> str:
    return 'L"' + text.replace('\\', '\\\\').replace('"', '\\"') + '"'


def _labels(labels: tuple[str, ...]) -> str:
    assert len(labels) == 4 and all(labels), labels
    return '{' + ','.join(_s(x) for x in labels) + '}'


def _float(x: float) -> str:
    return repr(mp.f32(x)) + 'f'


def _at(table: tuple, token: str) -> int:
    return -1 if token in ('', mp.NONE) else [x.token for x in table].index(token)


def render() -> str:
    out = ['// Generated by tools/gen_mech_parts.py from pylib/mech_parts.py: do not edit (CI checks it).',
           '// The custom mech parts (docs/feature-2026-11-21-mech-custom.md); src/mech_loadout.h includes it.',
           'inline constexpr MechFrame kMechFrames[]={']
    out += [f'    {{{_s(f.token)},{_s(f.file)},{_labels(f.labels)}}},' for f in mp.FRAMES]
    out += ['};', 'inline constexpr MechWeapon kMechWeapons[]={']
    out += [f'    {{{_s(w.token)},{_labels(w.labels)},MechMount::{w.slot},{str(w.right).lower()},{str(w.left).lower()},'
            f'{mp.cents(w.level)}}},' for w in mp.WEAPONS]
    out += ['};', 'inline constexpr MechCore kMechCores[]={']
    out += [f'    {{{_s(c.token)},{_labels(c.labels)},{mp.cents(c.level)}}},' for c in mp.CORES]
    out += ['};', 'inline constexpr MechRequest kMechRequests[]={']
    for r in mp.REQUESTS:
        weapons = ','.join(str(_at(mp.WEAPONS, t)) for t in r.slots)
        out.append(f'    {{{_s(r.token)},{_labels(r.labels)},{_s(r.vehicle)},{_float(r.level)},{mp.cents(r.level)},'
                   f'{_at(mp.FRAMES, r.frame)},{_at(mp.CORES, r.core)},{{{weapons}}}}},')
    out.append('};')
    return '\n'.join(out) + '\n'


def main(argv: list[str]) -> int:
    text = render()
    if '--check' in argv:
        try:
            with open(OUT, encoding='utf-8', newline='') as f:
                return 0 if f.read().replace('\r\n', '\n') == text else 1
        except FileNotFoundError:
            return 1
    with open(OUT, 'w', encoding='utf-8', newline='\n') as f:
        f.write(text)
    return 0


if __name__ == '__main__':
    sys.exit(main(sys.argv[1:]))
