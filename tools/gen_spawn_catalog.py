"""Writes src/spawn_catalog.inc, the object rows of the plugin's spawn catalog (src/debug_spawn.h kEntries: the M map's
「摆放」 panel in the test range and the debug spawn tool), and src/spawn_catalog_archives.h, the model archives that
catalog's preload can hold open at most (src/fsbudget.cpp sizes CRI's loader pool by it), from testrange/catalog.py:
EDF6's stock vehicles and enemies, the range's own vehicles, the installer's sedan, EDF5's DLC fortress and EDF4.1's
ported objects. The plugin's aircraft (support calls, the drone) and its support soldiers are written in
src/debug_spawn.h itself.

Each row carries the Mods files it needs (catalog.files_of, the list catalog.available checks): the plugin makes a Mods
row only when every one of them is there, the same test the range's own tools make.

The archive count is the distinct model archives (.MRAB / .RAB) the rows' SGOs name, through every SGO they name in turn
(catalog_archives.json, `--archives`: that needs the game's Root.cpk, so it is a committed record; tools/selftest.py
spawn_catalog_archives_recorded recomputes it where the game is).

  python tools/gen_spawn_catalog.py               write both
  python tools/gen_spawn_catalog.py --check       exit 1 when a committed file is not what this would write (CI)
  python tools/gen_spawn_catalog.py --archives    recompute testrange/catalog_archives.json from the game, then write
"""
from __future__ import annotations

import json
import os
import sys
from typing import Callable

HERE = os.path.dirname(os.path.abspath(__file__))
sys.path.insert(0, os.path.join(HERE, '..', 'pylib'))
sys.path.insert(0, os.path.join(HERE, '..', 'testrange'))
import catalog  # noqa: E402

OUT = os.path.normpath(os.path.join(HERE, '..', 'src', 'spawn_catalog.inc'))
OUT_ARCHIVES = os.path.normpath(os.path.join(HERE, '..', 'src', 'spawn_catalog_archives.h'))
ARCHIVES = os.path.normpath(os.path.join(HERE, '..', 'testrange', 'catalog_archives.json'))
HOW = {'vehicle': 'How::vehicle', 'ours': 'How::vehicle', 'enemy': 'How::enemy', 'enemy41': 'How::enemy'}
# The archives a model keeps open while its HD textures may stream (RandomAccessArchive::Open, docs/cri-fs-loaders-re.md):
# one CriFsLoader each for as long as the object's resources stay loaded.
MODEL_ARCHIVES = ('.MRAB', '.RAB')


def wide(text: str) -> str:
    return 'L"' + text.replace('\\', '\\\\').replace('"', '\\"') + '"'


def files_literal(row: catalog.Row) -> str:
    """The row's Mods files as the plugin checks them (debug_spawn.cpp ModRowLacks): names under Mods\\OBJECT\\, each
    ended by a NUL and the list by an empty one; nullptr for a stock row (Root.cpk's own)."""
    files = catalog.files_of(row)
    if row.source == 'stock':
        if files:
            raise ValueError(f'{row.sgo}: a stock row names Mods files')
        return 'nullptr'
    if row.rel not in files:
        raise ValueError(f'{row.sgo}: its own SGO {row.rel} is not among its files')
    names = []
    for rel in files:
        if not rel.startswith('OBJECT/') or '\\' in rel or '"' in rel or not rel.isascii():
            raise ValueError(f'{row.sgo}: {rel} is not a plain Mods/OBJECT path')
        names.append(rel.removeprefix('OBJECT/').replace('/', '\\\\'))
    # One literal a name (adjacent literals join): its \0 never runs on into the next name's first character.
    return ' '.join(f'L"{n}\\0"' for n in names)


def render() -> str:
    lines = ['// Generated by tools/gen_spawn_catalog.py from testrange/catalog.py. Do not edit.',
             '// {category, how, id (the log\'s), name (the panel\'s), SGO, arg, lift (m), a Mods file (not Root.cpk), preloaded by default,',
             '//  the Mods files it needs (under Mods\\OBJECT\\, each NUL-ended, the list ended by an empty one; catalog.files_of)}']
    for r in catalog.rows():
        if not r.ident.isascii() or '"' in r.ident:
            raise ValueError(f'{r.sgo}: the log id must be plain ASCII')
        lines.append(f'    {{Category::{r.category},{HOW[r.category]},"{r.ident}",{wide(r.label)},{wide(r.path)},0,{r.lift:.1f}f,'
                     f'{"true" if r.source != "stock" else "false"},{"true" if r.preload else "false"},{files_literal(r)}}},')
    return '\n'.join(lines) + '\n'


def recorded() -> dict[str, list[str]]:
    """catalog_archives.json's rows: each row's model archives (sorted Mods paths)."""
    with open(ARCHIVES, encoding='utf-8') as f:
        return json.load(f)['rows']


def archive_union(rows: dict[str, list[str]]) -> list[str]:
    """Every row's archives, each once (the game keeps one record per archive path: 0x1133C50)."""
    want = {r.sgo for r in catalog.rows()}
    if set(rows) != want:
        raise ValueError('testrange/catalog_archives.json is not the catalog\'s rows: python tools/gen_spawn_catalog.py --archives '
                         f'(missing {sorted(want - set(rows))[:4]}, extra {sorted(set(rows) - want)[:4]})')
    return sorted({a for archives in rows.values() for a in archives})


def render_archives() -> str:
    count = len(archive_union(recorded()))
    return '\n'.join([
        '// Generated by tools/gen_spawn_catalog.py from testrange/catalog_archives.json. Do not edit.',
        '// The distinct model archives (.MRAB / .RAB) every row of the spawn catalog (src/spawn_catalog.inc) names, through',
        '// every SGO it names: what the catalog\'s whole preload (ini RangePlaceAll=1) can keep open at once, one CriFsLoader',
        '// each (src/fsbudget.cpp, docs/cri-fs-loaders-re.md).',
        '#pragma once',
        '',
        'namespace crew::debugspawn {',
        f'inline constexpr int kCatalogModelArchives={count};',
        '}  // namespace crew::debugspawn',
        ''])


# ------------------------------------------------------------------------------------- the archives (needs the game)
def _strings(v: object) -> list[str]:
    if isinstance(v, str):
        return [v]
    if isinstance(v, dict):
        return [s for x in v.values() for s in _strings(x)]
    if isinstance(v, list):
        return [s for x in v for s in _strings(x)]
    return []


def _rel(app: str) -> str:
    """app:/Object/X.mrab -> OBJECT/X.MRAB."""
    return app.split(':/', 1)[-1].replace('\\', '/').strip('/').upper()


def row_archives(row: catalog.Row, read: Callable[[str], bytes | None]) -> list[str]:
    """The model archives `row`'s SGO names, through every SGO it names in turn (`read`: a Mods path's bytes as the
    game loads them, None when there is none). Raises when the row's own SGO cannot be read."""
    import sgo
    if read(row.rel) is None:
        raise FileNotFoundError(f'{row.sgo}: {row.rel} cannot be read (install the range / the installer\'s objects first)')
    seen: set[str] = set()
    found: set[str] = set()
    todo = [row.rel]
    while todo:
        rel = todo.pop()
        if rel in seen:
            continue
        seen.add(rel)
        data = read(rel)
        if data is None:
            continue
        try:
            members = sgo.load(data=data)
        except Exception:   # noqa: BLE001 - a file the reader does not parse names nothing to follow
            continue
        for s in _strings(members):
            if not s.lower().startswith('app:/'):
                continue
            ref = _rel(s)
            if ref.endswith('.SGO'):
                todo.append(ref)
            elif ref.endswith(MODEL_ARCHIVES):
                found.add(ref)
    return sorted(found)


def game_reader(root: str) -> Callable[[str], bytes | None]:
    """A Mods path's bytes as the game loads them: EDF4.1's ported files as the installer ships them, the range's own
    SGOs as its install writes them, the installer's other Mods files from Mods, else Root.cpk / Chunk0x.cpk."""
    sys.path.insert(0, HERE)
    import edf41_objects
    import gen
    import rootcpk
    reg = edf41_objects.registry()['files']
    archives = [rootcpk.Game(root)] + [rootcpk.Game(root, a) for a in ('Chunk01.cpk', 'Chunk02.cpk')
                                       if os.path.exists(os.path.join(root, a))]
    where: dict[str, object] = {}
    for g in reversed(archives):
        for d, n in g.cpk.index:
            where[f'{d.upper()}/{n.upper()}'] = g
    range_rows = {r.rel: r.sgo for r in catalog.rows() if r.source == 'range'}
    game = gen.Game(root)

    def read(rel: str) -> bytes | None:
        if rel in reg:
            return edf41_objects.read(rel)
        if rel in range_rows:
            return gen.vehicle_sgo(game, range_rows[rel])
        path = os.path.join(root, 'Mods', *rel.split('/'))
        if os.path.isfile(path):
            with open(path, 'rb') as f:
                return f.read()
        g = where.get(rel)
        if g is None:
            return None
        folder, name = rel.rsplit('/', 1)
        return g.read(folder, name)   # type: ignore[attr-defined]
    return read


def measure(root: str) -> dict[str, list[str]]:
    read = game_reader(root)
    return {r.sgo: row_archives(r, read) for r in catalog.rows()}


def write_archives(rows: dict[str, list[str]]) -> None:
    body = {'about': 'Each spawn catalog row\'s model archives (.MRAB / .RAB), through every SGO it names: '
                     'python tools/gen_spawn_catalog.py --archives (needs the game). src/spawn_catalog_archives.h counts them.',
            'rows': {k: rows[k] for k in sorted(rows)}}
    with open(ARCHIVES, 'w', encoding='utf-8', newline='\n') as f:
        json.dump(body, f, ensure_ascii=False, indent=1)
        f.write('\n')


def _same(path: str, text: str) -> bool:
    with open(path, encoding='utf-8', newline='') as f:
        return f.read().replace('\r\n', '\n') == text


def main(argv: list[str]) -> int:
    if '--archives' in argv:
        import rootcpk
        write_archives(measure(rootcpk.DEFAULT_GAME))
        print('wrote', ARCHIVES)
    outputs = ((OUT, render()), (OUT_ARCHIVES, render_archives()))
    if '--check' in argv:
        return 0 if all(_same(path, text) for path, text in outputs) else 1
    for path, text in outputs:
        with open(path, 'w', encoding='utf-8', newline='\n') as f:
            f.write(text)
        print('wrote', path)
    return 0


if __name__ == '__main__':
    sys.exit(main(sys.argv[1:]))
