"""Writes src/spawn_catalog.inc, the object rows of the plugin's spawn catalog (src/debug_spawn.h kEntries: the M map's
「摆放」 panel in the test range and the debug spawn tool), from testrange/catalog.py: EDF6's stock vehicles and enemies,
the range's own vehicles, the installer's sedan, EDF5's DLC fortress and EDF4.1's ported objects. The plugin's aircraft
(support calls, the drone) and its support soldiers are written in src/debug_spawn.h itself.

  python tools/gen_spawn_catalog.py            write it
  python tools/gen_spawn_catalog.py --check    exit 1 when the committed file is not what this would write (CI)
"""
from __future__ import annotations

import os
import sys

HERE = os.path.dirname(os.path.abspath(__file__))
sys.path.insert(0, os.path.join(HERE, '..', 'pylib'))
sys.path.insert(0, os.path.join(HERE, '..', 'testrange'))
import catalog  # noqa: E402

OUT = os.path.normpath(os.path.join(HERE, '..', 'src', 'spawn_catalog.inc'))
HOW = {'vehicle': 'How::vehicle', 'ours': 'How::vehicle', 'enemy': 'How::enemy', 'enemy41': 'How::enemy'}


def wide(text: str) -> str:
    return 'L"' + text.replace('\\', '\\\\').replace('"', '\\"') + '"'


def render() -> str:
    lines = ['// Generated by tools/gen_spawn_catalog.py from testrange/catalog.py. Do not edit.',
             '// {category, how, id (the log\'s), name (the panel\'s), SGO, arg, lift (m), a Mods file (not Root.cpk), preloaded by default}']
    for r in catalog.rows():
        if not r.ident.isascii() or '"' in r.ident:
            raise ValueError(f'{r.sgo}: the log id must be plain ASCII')
        lines.append(f'    {{Category::{r.category},{HOW[r.category]},"{r.ident}",{wide(r.label)},{wide(r.path)},0,{r.lift:.1f}f,'
                     f'{"true" if r.source != "stock" else "false"},{"true" if r.preload else "false"}}},')
    return '\n'.join(lines) + '\n'


def main(argv: list[str]) -> int:
    text = render()
    if '--check' in argv:
        with open(OUT, encoding='utf-8', newline='') as f:
            return 0 if f.read().replace('\r\n', '\n') == text else 1
    with open(OUT, 'w', encoding='utf-8', newline='\n') as f:
        f.write(text)
    print('wrote', OUT)
    return 0


if __name__ == '__main__':
    sys.exit(main(sys.argv[1:]))
