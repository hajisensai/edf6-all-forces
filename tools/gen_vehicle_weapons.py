"""Writes src/vehicle_weapons.inc: the weapon SGOs each stock vehicle the plugin preloads names (src/vehicle_weapons.h).

The game's resource preload (EDF+0x7A3780) of a vehicle's SGO does not take the weapon SGOs its vehicle_setup /
mission_setup name: those were read on the game thread when the vehicle was made (the SYNC LOAD probe, src/
sync_load_probe.cpp: 27 stock V_* weapons, 3.0 s, and 14 of the plugin's, 1.1 s, in one test range run). The plugin
queues them with their vehicle. A Mods vehicle's SGO (the plugin's, the range's, EDF4.1's, the loaded variants) is read
from Mods/OBJECT when it is preloaded; a stock one's is in Root.cpk, which the plugin does not read: its list is here.

The stock vehicles: every stock vehicle row of the spawn catalog (src/spawn_catalog.inc) and every support hull
(src/support_spawn.h kSupportVehicles). Each one's list is every `app:/weapon/....sgo` string its SGO holds, in the
SGO's own spelling (the game's resource names are as the SGO writes them), the first time each appears.

  python tools/gen_vehicle_weapons.py            write src/vehicle_weapons.inc from the game's Root.cpk
  python tools/gen_vehicle_weapons.py --check    exit 1 when the committed file is not what this would write; 77 without
                                                 the game (ctest vehicle_weapons_stock)
  python tools/gen_vehicle_weapons.py --covers   no game: exit 1 when a stock vehicle the plugin preloads has no row
                                                 (ctest vehicle_weapons_covers, CI)
"""
from __future__ import annotations

import os
import re
import sys

HERE = os.path.dirname(os.path.abspath(__file__))
ROOT = os.path.normpath(os.path.join(HERE, '..'))
OUT = os.path.join(ROOT, 'src', 'vehicle_weapons.inc')
CATALOG = os.path.join(ROOT, 'src', 'spawn_catalog.inc')
SUPPORT = os.path.join(ROOT, 'src', 'support_spawn.h')
WEAPON = re.compile(r'^app:/weapon/[^\0]+\.sgo$', re.IGNORECASE)


def read(path: str) -> str:
    with open(path, encoding='utf-8') as f:
        return f.read()


def stock_vehicles() -> list[str]:
    """The stock vehicles' object names (upper case, no extension), sorted."""
    names = set()
    for sgo, mod in re.findall(r'\{Category::\w+,How::vehicle,"[^"]*",L"[^"]*",L"app:/object/([^"]+)",[^,]*,[^,]*,(true|false),',
                               read(CATALOG)):
        if mod == 'false':
            names.add(sgo.rsplit('.', 1)[0].upper())
    support = read(SUPPORT)
    body = support[support.index('kSupportVehicles[]='):]
    body = body[:body.index('};')]
    for sgo in re.findall(r'L"app:/Object/([^"]+)"', body, re.IGNORECASE):
        names.add(sgo.rsplit('.', 1)[0].upper())
    if not names:
        raise SystemExit('gen_vehicle_weapons: no stock vehicle found (the catalog or support_spawn.h changed form)')
    return sorted(names)


def weapons_of(data: bytes) -> list[str]:
    """Every app:/weapon/*.sgo string of an SGO, in its order, each once (by its lower-case spelling)."""
    sys.path.insert(0, os.path.join(ROOT, 'pylib'))
    import sgo  # noqa: E402
    found: list[str] = []
    seen: set[str] = set()

    def walk(v) -> None:
        if isinstance(v, dict):
            for x in v.values():
                walk(x)
        elif isinstance(v, (list, tuple)):
            for x in v:
                walk(x)
        elif isinstance(v, str) and WEAPON.match(v) and v.lower() not in seen:
            seen.add(v.lower())
            found.append(v)
    walk(sgo.load(data=data))
    return found


def literal(s: str) -> str:
    assert all(0x20 <= ord(c) < 0x7F and c not in '"\\' for c in s), s
    return s


def render(rows: list[tuple[str, list[str]]]) -> str:
    out = ['// Generated by tools/gen_vehicle_weapons.py from the game\'s Root.cpk. Do not edit.',
           '// {a stock vehicle\'s object name (upper case, no extension), its SGO\'s app:/weapon/ files: each NUL-ended,',
           '//  the list ended by an empty one}']
    for name, weapons in rows:
        listed = ''.join(literal(w) + '\\0' for w in weapons)
        out.append(f'    {{L"{literal(name)}",L"{listed}"}},')
    return '\n'.join(out) + '\n'


def rows_from_game() -> list[tuple[str, list[str]]] | None:
    sys.path.insert(0, os.path.join(ROOT, 'pylib'))
    import rootcpk  # noqa: E402
    if not os.path.isfile(os.path.join(rootcpk.DEFAULT_GAME, 'Root.cpk')):
        return None
    game = rootcpk.Game(rootcpk.DEFAULT_GAME)
    return [(name, weapons_of(game.read('OBJECT', name + '.SGO'))) for name in stock_vehicles()]


def main(argv: list[str]) -> int:
    if argv == ['--covers']:
        have = set(re.findall(r'^\s*\{L"([^"]+)",', read(OUT), re.MULTILINE))
        lacking = [n for n in stock_vehicles() if n not in have]
        if lacking:
            print('vehicle_weapons.inc lacks ' + ', '.join(lacking) + ': run python tools/gen_vehicle_weapons.py (with the game)')
            return 1
        print(f'gen_vehicle_weapons --covers: {len(have)} stock vehicles, every one the plugin preloads')
        return 0
    if argv not in ([], ['--check']):
        print(__doc__)
        return 2
    rows = rows_from_game()
    if rows is None:
        print('SKIP: the game\'s Root.cpk is not here')
        return 77
    text = render(rows)
    if argv == ['--check']:
        if read(OUT) != text:
            print('src/vehicle_weapons.inc is stale: run python tools/gen_vehicle_weapons.py and commit it')
            return 1
        print(f'gen_vehicle_weapons --check: {len(rows)} stock vehicles, {sum(len(w) for _, w in rows)} weapon files, as Root.cpk')
        return 0
    with open(OUT, 'w', encoding='utf-8', newline='\n') as f:
        f.write(text)
    print(f'wrote {OUT}: {len(rows)} stock vehicles, {sum(len(w) for _, w in rows)} weapon files')
    return 0


if __name__ == '__main__':
    raise SystemExit(main(sys.argv[1:]))
