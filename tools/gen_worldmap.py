"""Generate src/worldmap.inc: the world map's places and every mission key's place (src/worldmap_logic.h).

  python -B tools/gen_worldmap.py            write src/worldmap.inc
  python -B tools/gen_worldmap.py --check    fail (exit 1) when the committed file is stale; writes nothing

Inputs, both in the repository (no game needed): pylib/worldmap.py (PLACES, MAPS: map -> real place) and
worldmap/missions.json (tools/make_worldmap.py: the map every mission loads). A mission whose map MAPS does not name,
or one key on two places, stops the generation.
"""
from __future__ import annotations

import argparse
import json
from pathlib import Path
import sys

ROOT = Path(__file__).resolve().parents[1]
sys.dont_write_bytecode = True
sys.path.insert(0, str(ROOT / 'pylib'))
import worldmap  # noqa: E402

OUT = ROOT / 'src' / 'worldmap.inc'
MISSIONS = ROOT / 'worldmap' / 'missions.json'


def _w(s: str) -> str:
    return 'L"' + s.replace('\\', '\\\\').replace('"', '\\"') + '"'


def _f(x: float) -> str:
    return f'{x:.3f}f'


def missions() -> list[tuple[str, str, str]]:
    """(key, place id, map) per distinct key, in pack / list order."""
    data = json.loads(MISSIONS.read_text(encoding='utf-8'))
    seen: dict[str, str] = {}
    out = []
    for pack in data['packs']:
        for m in pack['missions']:
            key, place = m['key'], worldmap.place_of_map(m['map'])
            if key.upper() in seen:
                if seen[key.upper()] != place:
                    raise SystemExit(f'{key}: two places ({seen[key.upper()]}, {place})')
                continue
            seen[key.upper()] = place
            out.append((key, place, m['map']))
    return out


def render() -> str:
    ids = list(worldmap.PLACES)
    used = {p for _, p, _ in missions()} | {worldmap.RANGE_PLACE}
    unused = [i for i in ids if i not in used]
    if unused:
        raise SystemExit(f'places no mission stands on: {unused}')
    lines = ['// Generated by tools/gen_worldmap.py from pylib/worldmap.py and worldmap/missions.json. Do not edit.',
             '// Included inside namespace worldmap by src/worldmap_logic.h.',
             'inline constexpr Place kPlaces[]={']
    for i in ids:
        p = worldmap.PLACES[i]
        names = ','.join(_w(n) for n in (p.en, p.sc, p.tc, p.ja))
        lines.append(f'    {{{_f(p.lat)},{_f(p.lon)},Region::{p.region},{_w(i)},{{{names}}}}},')
    lines.append('};')
    lines.append('inline constexpr Mission kMissions[]={')
    for key, place, name in missions():
        lines.append(f'    {{{_w(key)},{ids.index(place)}}},   // {name}')
    lines.append('};')
    lines.append(f'inline constexpr const wchar_t* kRangeKeyPrefix={_w(worldmap.RANGE_KEY_PREFIX)};')
    lines.append(f'inline constexpr int kRangePlace={ids.index(worldmap.RANGE_PLACE)};   // {worldmap.RANGE_PLACE}')
    return '\n'.join(lines) + '\n'


def main(argv: list[str]) -> int:
    ap = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    ap.add_argument('--check', action='store_true')
    args = ap.parse_args(argv)
    text = render()
    if args.check:
        have = OUT.read_text(encoding='utf-8') if OUT.exists() else ''
        if have != text:
            print(f'{OUT} is stale: run python tools/gen_worldmap.py and commit it')
            return 1
        return 0
    OUT.write_bytes(text.encode('utf-8'))
    print(f'{OUT}: {len(worldmap.PLACES)} places, {len(missions())} missions')
    return 0


if __name__ == '__main__':
    sys.exit(main(sys.argv[1:]))
