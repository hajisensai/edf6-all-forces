"""Writes src/zw_vehicles.inc, the plugin's table of the Vehicler's vehicles (src/zw_vehicle_catalog.h ZwVehicleSpec), from
pylib/zw_vehicles.py: per vehicle, in the registry's order (its index is the vehicle's number: preload item, plan
resource), its weapon row id, the vehicle SGO's path as the plugin spawns it and its Mods/OBJECT file name, the native
class's vtable (zw_vehicles.CLASS_VTABLES by the hull's class: tests/zw_vehicles_test.py checks the built SGO says that
class), its seats, its envelope (half width, half length, height, metres), its logistics cost and the firepower curve.

  python tools/gen_zw_vehicles.py            write it
  python tools/gen_zw_vehicles.py --check    exit 1 when the committed file is not what this would write (CI, ctest)
"""
from __future__ import annotations

import os
import sys

HERE = os.path.dirname(os.path.abspath(__file__))
sys.path.insert(0, os.path.join(HERE, '..', 'pylib'))
import zw_vehicles as zv  # noqa: E402

OUT = os.path.normpath(os.path.join(HERE, '..', 'src', 'zw_vehicles.inc'))


def _wstr(s: str) -> str:
    return 'L"' + s.replace('\\', '\\\\').replace('"', '\\"') + '"'


def _f(x: float) -> str:
    return f'{x:.2f}f'


def render() -> str:
    lines = ['// Generated by tools/gen_zw_vehicles.py from pylib/zw_vehicles.py: do not edit.',
             '// { weapon row, vehicle SGO, Mods/OBJECT file, vtable, seats, halfWidth, halfLength, height, logisticsCost, curve }']
    for v in zv.VEHICLES:
        cells = [_wstr(v.row), _wstr(v.path), _wstr(f'{v.sgo.upper()}.SGO'), f'0x{v.vtable:X}u', f'{v.seats}u',
                 *(_f(x) for x in v.envelope), f'{v.logistics_cost}u', f'supportlevel::Curve::{v.curve}']
        lines.append('{' + ','.join(cells) + '},   // ' + v.cls + (' (placeholder model)' if v.state == 'placeholder'
                                                                    else ''))
    return '\n'.join(lines) + '\n'


def main(argv: list[str]) -> int:
    text = render()
    current = None
    if os.path.isfile(OUT):
        with open(OUT, encoding='utf-8', newline='') as f:
            current = f.read().replace('\r\n', '\n')
    if '--check' in argv:
        if current != text:
            print(f'{OUT} is stale: run python tools/gen_zw_vehicles.py and commit it')
            return 1
        print(f'{OUT} is current')
        return 0
    if current != text:
        with open(OUT, 'w', encoding='utf-8', newline='\n') as f:
            f.write(text)
        print(f'wrote {OUT}')
    return 0


if __name__ == '__main__':
    sys.exit(main(sys.argv[1:]))
