"""The colours the game's own HQ colour-select screen offers (HUiHQColorSelect, vtable 0x1800C40), as the room / HQ loadout
menu's palette (src/room_menu.h kDefaultPalette, docs/feature-2026-10-12-room-loadout-menu.md 阶段 4b).

Where they come from (EDF.dll 0x678CCB46, static RE):
  DEFAULTPACKAGE/CONFIG.SGO SoldierInit[class][5][0]  the class's colour file, App:/DefaultPackage/CustomColor<Class>.sgo (0xE07D0)
  CustomColor                           12 entries x 2 channels (primary, secondary) x RGBA floats
  0xDF1B0                               copies them into GameStatus +0x6FB0 (per player x class x outfit x channel)
  HUiHQColorSelect 0x881060 / 0x880F50  shows the 12 of each channel as chips (0x880010 -> 0x824D40 "ColorChipBox")
Entries 4..11 are the same in every class; 0..3 are the class's own.

The menu has one colour cycle for both fields, so the palette is (stock first, src/room_menu.h CycleColour):
  the shared entries 4..11, each entry's primary then its secondary; then the class entries 0..3 of Ranger, Wing Diver,
  Fencer (the support soldiers' classes; the Air Raider's are left out: no support soldier is one), primary then
  secondary; a colour already in the list is not repeated. Each float to 0..255 rounded half up.

  python tools/hq_palette.py [game dir]            print the table
  python tools/hq_palette.py [game dir] --write    write src/hq_palette.inc
"""
from __future__ import annotations

import os
import sys

HERE = os.path.dirname(os.path.abspath(__file__))
ROOT = os.path.dirname(HERE)
sys.path.insert(0, os.path.join(ROOT, 'pylib'))
import rootcpk  # noqa: E402
import sgo  # noqa: E402

INC = os.path.join(ROOT, 'src', 'hq_palette.inc')
# CONFIG.SGO SoldierInit's class order (0 Ranger, 1 Wing Diver, 2 Air Raider, 3 Fencer) and the files they name.
CLASS_FILES = ('CUSTOMCOLORRANGER.SGO', 'CUSTOMCOLORWINGDIVER.SGO', 'CUSTOMCOLORAIRRAIDER.SGO', 'CUSTOMCOLORHEAVYARMOR.SGO')
SUPPORT_CLASSES = (0, 1, 3)   # the classes support soldiers are (src/support_loadout.h SupportSoldierClass: Ranger, Wing Diver, Fencer)
SHARED = range(4, 12)
OWN = range(0, 4)
ENTRIES = 12


def _float(f: object) -> float:
    return f.value if isinstance(f, sgo.Float) else float(f)


def _byte(f: object) -> int:
    v = int(_float(f) * 255.0 + 0.5)
    return 0 if v < 0 else 255 if v > 255 else v


def rgb(colour: list) -> int:
    """An RGBA float4 as 0xRRGGBB (alpha dropped: every entry's is 1.0)."""
    r, g, b = (_byte(colour[i]) for i in range(3))
    return (r << 16) | (g << 8) | b


def class_table(game: rootcpk.Game, cls: int) -> list[tuple[int, int]]:
    """Class `cls`'s 12 (primary, secondary) pairs, from its CustomColor file."""
    _, members = sgo.read(game.read('DEFAULTPACKAGE', CLASS_FILES[cls]))
    table = members['CustomColor']
    if len(table) != ENTRIES or any(len(e) != 2 or any(len(c) != 4 for c in e) for e in table):
        raise ValueError(f'{CLASS_FILES[cls]}: CustomColor is not 12 x 2 x RGBA')
    if any(abs(_float(c[3]) - 1.0) > 1e-6 for e in table for c in e):
        raise ValueError(f'{CLASS_FILES[cls]}: an alpha is not 1')
    return [(rgb(e[0]), rgb(e[1])) for e in table]


def config_files(game: rootcpk.Game) -> list[str]:
    """CONFIG.SGO SoldierInit[class][5][0] for each class: the colour files the game loads."""
    _, members = sgo.read(game.read('DEFAULTPACKAGE', 'CONFIG.SGO'))
    return [str(entry[5][0]) for entry in members['SoldierInit']]


def palette(game: rootcpk.Game) -> list[tuple[int, str]]:
    """[(0xRRGGBB, where it came from)] in the menu's order."""
    tables = {cls: class_table(game, cls) for cls in range(4)}
    for cls in range(1, 4):
        if [tables[cls][i] for i in SHARED] != [tables[0][i] for i in SHARED]:
            raise ValueError(f'{CLASS_FILES[cls]}: entries 4..11 differ from the Ranger\'s')
    out: list[tuple[int, str]] = []
    seen: set[int] = set()

    def add(colour: int, why: str) -> None:
        if colour not in seen:
            seen.add(colour)
            out.append((colour, why))

    for i in SHARED:
        add(tables[0][i][0], f'all classes #{i} primary')
        add(tables[0][i][1], f'all classes #{i} secondary')
    names = {0: 'Ranger', 1: 'Wing Diver', 3: 'Fencer'}
    for cls in SUPPORT_CLASSES:
        for i in OWN:
            add(tables[cls][i][0], f'{names[cls]} #{i} primary')
            add(tables[cls][i][1], f'{names[cls]} #{i} secondary')
    return out


def render(entries: list[tuple[int, str]]) -> str:
    lines = ['// Generated by tools/hq_palette.py from Root.cpk DEFAULTPACKAGE/CUSTOMCOLOR*.SGO (CustomColor): the HQ colour-select',
             '// screen\'s chips, in the room menu\'s order. Do not edit; tests/hq_palette_audit.py checks it against the game.',
             f'// {len(entries)} colours.']
    for colour, why in entries:
        lines.append(f'0x{colour:06X},   // {why}')
    return '\n'.join(lines) + '\n'


def main(argv: list[str]) -> int:
    args = [a for a in argv if not a.startswith('--')]
    game = rootcpk.Game(args[0]) if args else rootcpk.default()
    text = render(palette(game))
    if '--write' in argv:
        with open(INC, 'w', encoding='utf-8', newline='\n') as f:
            f.write(text)
        print('写入', INC)
    else:
        print(text, end='')
    return 0


if __name__ == '__main__':
    sys.exit(main(sys.argv[1:]))
