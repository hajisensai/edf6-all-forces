TEAMS = {'TEAM_ID_ENEMY': '敌方', 'TEAM_ID_FRIEND': '友方', 'TEAM_ID_PLAYER': '玩家方'}
LEVELS = {'MISSION_DIFFICULTY_EASY': '简单', 'MISSION_DIFFICULTY_NORMAL': '普通', 'MISSION_DIFFICULTY_HARD': '困难',
          'MISSION_DIFFICULTY_HARDEST': '极难', 'MISSION_DIFFICULTY_INFERNO': '炼狱'}


def _args(text: str) -> list[str]:
    """Top-level arguments of a call's text 'Name(a, f(b, c), "d,e")' (comments already removed)."""
    inner = text[text.index('(') + 1:text.rindex(')')]
    out, depth, cur, quote = [], 0, '', False
    for ch in inner:
        if ch == '"':
            quote = not quote
        if not quote and ch in '([{':
            depth += 1
        if not quote and ch in ')]}':
            depth -= 1
        if ch == ',' and depth == 0 and not quote:
            out.append(cur.strip())
            cur = ''
        else:
            cur += ch
    if cur.strip():
        out.append(cur.strip())
    return out


def _plain(a: str) -> str:
    a = a.strip().strip('"')
    return TEAMS.get(a, LEVELS.get(a, a))


