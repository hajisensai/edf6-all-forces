# Statements that are the event editor's scaffolding or loading/lighting detail, not the mission's content.
NOISE = re.compile(r'^(::|internal_|__|IsBoolState|Mutex_|WaitVoice\(\)|g_soldiers\s*=\s*GetTalkers|Preload|WaitPreload|'
                   r'BeginLoading|EndLoading|Online_WaitStart|EventLightTool\b|tool\.|const uint32 MAX_EVENT_ID|'
                   r'\w+_usercode\(\);|if\(\s*::__\w+_data\.m_counter\b)')
# Only the editor's own guard (`if( ::__XXXX_data.m_counter != 1 ) return;`) goes: a script's own `if (...) return;`
# is a condition the reader needs.
# Dropped ideas (code switched off, debug-only placeholder text, superseded dialogue, events nothing starts) are
# kept but marked: a digest line starting with DEAD is shown greyed on the site.
DEAD = '⊘ '
DEAD_COMMENT = '//⊘ '
DEBUG_TEXT = re.compile(r'^DebugMessageW\(\s*"([^"]*)"')
# Presentation only (animation, facing, camera, chatter switches): left out of the digest.
SHOW = re.compile(r'(^|\.)(AppealAnimation\w*|SetAiObjectDirection_\w+|ClearAiObjectDirection|LookCameraTo\w+|CloseUi|'
                  r'SetCharacterRandomTalk|EnableAiRandomTalk|DisableAiRandomTalk|TalkBegin|TalkEnd|EnvFadeAnimation)\s*\(')
# A // comment that is code switched off rather than a note.
CODE_COMMENT = re.compile(r'^//\s*([A-Za-z_:][A-Za-z0-9_.:\[\]]*\s*(\(|=[^=])|[A-Za-z_:].*;\s*(//.*)?$)', re.ASCII)
# ASCII identifiers only: a Japanese note like `// 増援(2波目)` or `// 敵数=10` is a note, not switched-off code.
SPEECH = re.compile(r'^(Speak_\w+|RadioVoice|Talk_\w+)\s*\(')
NUM_F = re.compile(r'\b(\d+(?:\.\d+)?)f\b')
DROP_COMMENTS = re.compile(r'^//\s*(\[e2d_section_data\]|ゲーム進行スクリプト|音声スクリプト|-{5,})')
EVENT = re.compile(r'internal_CreateEvent\(\s*"__([0-9A-Fa-f]{4})_game_event"\s*,\s*"([^"]*)"\s*,[^,]*,\s*(EVENT_TYPE_\w+)\s*,\s*(EVENT_CHECK_\w+)')


def mark_block_comments(text: str) -> str:
    """/* ... */ spanning lines or longer than a label is code the developers switched off: each of its lines
    becomes a `//⊘` comment (shown greyed as a dropped idea). One-line argument labels /*名*/ stay as they are."""
    def mark(m: re.Match) -> str:
        body = m.group(0)[2:-2]
        if '\n' not in body and len(body) <= 30:
            return f'/*{body.strip()}*/'
        return '\n' + '\n'.join(DEAD_COMMENT + x.strip() for x in body.split('\n') if x.strip()) + '\n'
    return re.sub(r'/\*.*?\*/', mark, text, flags=re.S)


def functions(text: str) -> dict[str, str]:
    """Top-level function bodies by name, brace matched outside // comments and strings (switched-off code in
    comments holds braces)."""
    out: dict[str, str] = {}
    for m in re.finditer(r'^void\s+(\w+)\s*\(\s*\)\s*\n\{', text, flags=re.M):
        depth, i = 1, m.end()
        while depth and i < len(text):
            c = text[i]
            if c == '/' and text.startswith('//', i):
                i = text.find('\n', i)
                i = len(text) if i < 0 else i
                continue
            if c == '"':
                i = text.find('"', i + 1) + 1 or len(text)
                continue
            depth += {'{': 1, '}': -1}.get(c, 0)
            i += 1
        out[m.group(1)] = text[m.end():i - 1]
    return out


def statements(body: str) -> list[tuple[int, str]]:
    """(indent, statement) with multi-line calls joined; a continuation line's // comment becomes /*...*/ after its
    own argument. Switched-off code (`//⊘` lines, // comments that are code, and the lines continuing such a
    call) is joined the same way and comes out as one `//⊘` statement."""
    out: list[tuple[int, str]] = []
    pending: list | None = None   # [indent, text, depth, dead]

    def flush() -> None:
        nonlocal pending
        if pending:
            out.append((pending[0], (DEAD_COMMENT if pending[3] else '') + pending[1]))
        pending = None

    for raw in body.split('\n'):
        line = raw.strip()
        if not line:
            continue
        indent = len(raw) - len(raw.lstrip('\t'))
        dead = False
        if line.startswith(DEAD_COMMENT.strip()):
            dead, line = True, line[len(DEAD_COMMENT.strip()):].strip()
        elif line.startswith('//') and (CODE_COMMENT.match(line) or (pending and pending[3])):
            dead, line = True, line[2:].strip()
        if pending and dead != pending[3]:
            flush()
        if pending:
            code, _, note = line.partition('//')
            code = code.strip()
            label = f' /*{note.strip()}*/' if note.strip() else ''
            pending[1] += ' ' + (code[:-1] + label + ',' if label and code.endswith(',') else code + label)
            pending[2] += code.count('(') - code.count(')')
            if pending[2] <= 0:
                flush()
            continue
        if not dead and line.startswith('//'):
            out.append((indent, line))
            continue
        code = line.split('//')[0]
        d = code.count('(') - code.count(')')
        if d > 0:
            pending = [indent, code.strip(), d, dead]
            continue
        out.append((indent, (DEAD_COMMENT if dead else '') + line))
    flush()
    return out


@dataclass
class Link:
    target: int
    name: str
    check: str
    conds: list[str] = field(default_factory=list)


@dataclass
class Part:
    lines: list[str] = field(default_factory=list)
    links: list[Link] = field(default_factory=list)


def factor(call: str) -> str:
    name = call.split('(')[0].split('.')[-1]
    plain = re.sub(r'/\*.*?\*/', '', call)
    try:
        args = [NUM_F.sub(r'\1', x) for x in _args(plain)]
        if name in FACTORS:
            return f'{FACTORS[name](args)}（{name}）'
    except (IndexError, ValueError):
        pass
    return NUM_F.sub(r'\1', plain.removeprefix('e.').rstrip(';').strip())


def readable(stmt: str) -> str:
    return NUM_F.sub(r'\1', re.sub(r'"app:/(?:object|Object)/([^"]+?)\.sgo"', r'\1', stmt))


