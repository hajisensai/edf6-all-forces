# ------------------------------------------------------------------ voices

Voices = dict[str, tuple[str, str]]


def voices(game: rootcpk.Game) -> Voices:
    """Voice id -> (speaker, SC caption): the id table names each row index, the language table holds the row."""
    ids = dsgo.parse(game.read('MISSION', 'EDF6_VOICETABLE.SGO')).root.items[0]
    rows = dsgo.parse(game.read('MISSION', 'EDF6_VOICETABLE.SC.SGO')).root.items[0].items
    out: Voices = {}
    for i, vid in ids.names.items():
        if i < len(rows) and isinstance(rows[i], dsgo.Node) and len(rows[i].items) >= 2:
            out[vid] = (str(rows[i].items[0]), str(rows[i].items[1]).replace('\n', ' '))
    return out


def say(vid: str, table: Voices) -> str:
    who, text = table[vid]
    return f'{who}：「{text}」'


