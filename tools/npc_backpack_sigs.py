"""The code an NPC's backpack weapon rests on (src/npc_backpack.cpp, docs/npc-backpack-re.md), as byte signatures read
from EDF.dll (TimeDateStamp 0x678CCB46): writes src/npc_backpack_signatures.inc. tests/npc_backpack_native_audit.py
checks the .inc against the game's EDF.dll and decodes what the plugin relies on (the gate, the offsets, the call
targets, the message).

    python tools/npc_backpack_sigs.py [EDF.dll]
"""
from __future__ import annotations

