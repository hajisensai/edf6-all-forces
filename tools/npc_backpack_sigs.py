import sys

import pefile

HERE = os.path.dirname(os.path.abspath(__file__))
sys.path.insert(0, os.path.join(HERE, '..', 'pylib'))
import gamedir  # noqa: E402

INC = os.path.join(HERE, '..', 'src', 'npc_backpack_signatures.inc')
TIMESTAMP = 0x678CCB46

