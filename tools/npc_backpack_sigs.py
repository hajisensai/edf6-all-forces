def image(path: str) -> tuple[pefile.PE, bytes]:
    pe = pefile.PE(path, fast_load=True)
    if pe.FILE_HEADER.TimeDateStamp != TIMESTAMP:
        raise ValueError(f'EDF.dll TimeDateStamp {pe.FILE_HEADER.TimeDateStamp:#x}, not {TIMESTAMP:#x}')
    return pe, pe.get_memory_mapped_image()


def render(img: bytes) -> str:
    lines = ['// Generated by tools/npc_backpack_sigs.py from EDF.dll 0x678CCB46: do not edit. (npc_backpack.cpp InstallNpcBackpack)']
    for i, (rva, size, what) in enumerate(SIGNATURES):
        data = ','.join(f'0x{b:02X}' for b in img[rva:rva + size])
        lines.append(f'// {what}')
        lines.append(f'constexpr unsigned char kSig{i}[]={{{data}}};')
    lines.append('constexpr Signature kSignatures[]={')
    lines += [f'    {{0x{rva:X},kSig{i},sizeof(kSig{i})}},' for i, (rva, _, _) in enumerate(SIGNATURES)]
    lines.append('};')
    return '\n'.join(lines) + '\n'


def main(argv: list[str]) -> int:
    path = argv[1] if len(argv) > 1 else os.path.join(gamedir.find_or_dev(), 'EDF.dll')
    _, img = image(path)
    with open(INC, 'w', encoding='utf-8', newline='\n') as f:
        f.write(render(img))
    print(f'wrote {INC}: {len(SIGNATURES)} signatures')
    return 0


if __name__ == '__main__':
    raise SystemExit(main(sys.argv))
