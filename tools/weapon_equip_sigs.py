"""The code the 整备 weapons page's equip rests on (src/weapon_equip.cpp, docs/weapon-select-re.md), as byte signatures
read from EDF.dll (TimeDateStamp 0x678CCB46): writes src/weapon_equip_signatures.inc. tests/weapon_equip_native_audit.py
checks the .inc against the game's EDF.dll and the generated weapon data against the game's tables.

The functions weapon_equip.cpp calls, and the stock weapon select screen's code whose rules it repeats (a change there
means the rules may have changed: the module stays off).

    python tools/weapon_equip_sigs.py [EDF.dll]
"""
from __future__ import annotations

import os
import sys

HERE = os.path.dirname(os.path.abspath(__file__))
sys.path.insert(0, HERE)
import room_preview_sigs  # noqa: E402  (image(): the TimeDateStamp check)

INC = os.path.join(HERE, '..', 'src', 'weapon_equip_signatures.inc')

# (rva, size, what it holds)
SIGNATURES: tuple[tuple[int, int, str], ...] = (
    # Called.
    (0x0E23F0, 0x14, 'WeaponTable RowCount(cfg): [cfg+0x188] the table node'),
    (0x0E1CF0, 0x1B, 'WeaponTable GetRow(cfg, Row* out, id): no bounds check'),
    (0x0E1BA0, 0x14, 'WeaponTable FindRow(cfg, const wchar_t*): -1 when not there'),
    (0x0E20B9, 0x28, 'GetRow: +0x20 = max(0, (int)(col4 * 0.25f * 100.0f)), the level shown and capped'),
    (0x0D8850, 0x30, 'the weapon level cap (GS): difficulty GS+0x4C, progress 0xD7B60, jmp 0xE2710'),
    (0x119D1B0, 0x1C, 'the UI system broadcast (system, message id, payload*)'),
    # The stock screen (HUiHQWeaponSelect) whose rules the write repeats.
    (0x8BC850, 0x29, 'the cap predicate: byte GS+0x14FC8 && (unsigned)level > 0xD8850(GS)'),
    (0x8B5145, 0x3C, 'list build: +0xE528 (the slot may repeat) 0: an item in the class\'s other slots (and not this '
                     'slot\'s) gets state 2 at +0x4F4'),
    (0x8BD7E3, 0x20, 'confirm: the snapshot written back, memcpy(target ?: GS+0x6E68, this+0x800, 0xDCE8)'),
    (0x8BDA26, 0x36, 'confirm: 0x8BB920(this, &player +0x7B0, _, &slot +0x7B4, &row), +0xE628 = 1, close 0x7E2EB0'),
    (0x8BB939, 0xB8, 'msg 4 sender: payload {player, slot, row, class (snapshot +0x828)}, 0x119D1B0(system = '
                     '[0x20B2960] - 0x88, 4, &payload)'),
)


def render(img: bytes) -> str:
    lines = ['// Generated by tools/weapon_equip_sigs.py from EDF.dll 0x678CCB46: do not edit. (weapon_equip.cpp CheckCode)']
    for i, (rva, size, what) in enumerate(SIGNATURES):
        data = ','.join(f'0x{b:02X}' for b in img[rva:rva + size])
        lines.append(f'// {what}')
        lines.append(f'constexpr unsigned char kSig{i}[]={{{data}}};')
    lines.append('constexpr Signature kSignatures[]={')
    lines += [f'    {{0x{rva:X},kSig{i},sizeof(kSig{i})}},' for i, (rva, _, _) in enumerate(SIGNATURES)]
    lines.append('};')
    return '\n'.join(lines) + '\n'


def main(argv: list[str]) -> int:
    import gamedir
    path = argv[1] if len(argv) > 1 else os.path.join(gamedir.find_or_dev(), 'EDF.dll')
    _, img = room_preview_sigs.image(path)
    with open(INC, 'w', encoding='utf-8', newline='\n') as f:
        f.write(render(img))
    print(f'wrote {os.path.normpath(INC)}: {len(SIGNATURES)} signatures')
    return 0


if __name__ == '__main__':
    sys.exit(main(sys.argv))
